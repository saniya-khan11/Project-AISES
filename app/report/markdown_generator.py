import json
from pathlib import Path


class MarkdownReportGenerator:
    """
    Generates a professional Markdown report
    from the AISES JSON report.
    """

    def generate(
        self,
        report_json="outputs/report.json",
        output_file="outputs/report.md"
    ):

        print("=" * 80)
        print("AISES MARKDOWN REPORT")
        print("=" * 80)

        with open(report_json, encoding="utf-8") as fp:
            report = json.load(fp)

        summary = report["summary"]

        md = []

        # ======================================================
        # Cover
        # ======================================================

        md.append("# AISES Software Evaluation Report\n")

        md.append("Automatically Generated by AISES\n")

        md.append("---\n")

        # ======================================================
        # Executive Summary
        # ======================================================

        md.append("## Executive Summary\n")

        md.append("| Metric | Value |")
        md.append("|--------|------:|")

        md.append(f"| Total Requirements | {summary['total_requirements']} |")
        md.append(f"| Implemented | {summary['implemented']} |")
        md.append(f"| Partially Implemented | {summary['partially_implemented']} |")
        md.append(f"| Not Implemented | {summary['not_implemented']} |")
        md.append(f"| Overall Compliance | {summary['overall_compliance']}% |")

        md.append("\n---\n")

        # ======================================================
        # Requirement Details
        # ======================================================

        md.append("# Requirement Traceability Matrix\n")

        for req in report["requirements"]:

            md.append(f"## {req['ac_id']}")

            md.append(f"### Requirement")
            md.append(req["requirement_title"])

            md.append("\n### Description")
            md.append(req["description"])

            md.append("\n### Evaluation")

            md.append(f"- **Status:** {req['status']}")
            md.append(f"- **Confidence:** {req['confidence']}")
            md.append(f"- **Coverage:** {req['coverage']}%")

            md.append("\n### Matched Files")

            if req["matched_files"]:
                for file in req["matched_files"]:
                    md.append(f"- {file}")
            else:
                md.append("- None")

            md.append("\n### Strengths")

            if req["strengths"]:
                for item in req["strengths"]:
                    md.append(f"- {item}")
            else:
                md.append("- None")

            md.append("\n### Issues")

            if req["issues"]:
                for item in req["issues"]:
                    md.append(f"- {item}")
            else:
                md.append("- None")

            md.append("\n### Recommendations")

            if req["recommendations"]:
                for item in req["recommendations"]:
                    md.append(f"- {item}")
            else:
                md.append("- None")

            md.append("\n---\n")

        Path(output_file).write_text(
            "\n".join(md),
            encoding="utf-8"
        )

        print(f"Saved : {output_file}")

        return output_file